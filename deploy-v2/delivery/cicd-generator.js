/**
 * CI/CD Pipeline Generation (CI/CD Spec, all 5 Requirements)
 * 
 * Generates GitHub Actions / GitLab CI workflows that:
 * 1. Run the SAME validation gate modules as pre-return checks
 * 2. Default to mocked/sandboxed infra (never real accounts in CI)
 * 3. Gate by environment (dev → stage → prod with human approval)
 * 4. Classify failures into a fixed taxonomy
 * 5. Run regression suite on every agent change
 * 
 * Key principle: CI invokes the actual validation gate modules as
 * test steps (pytest tests/validation/) — no reimplementation.
 */

'use strict';

// ============================================================
// FAILURE TAXONOMY (Requirement 4)
// ============================================================

const FAILURE_TAXONOMY = [
  'syntax_error',
  'hallucinated_api',
  'platform_import_violation',
  'mocked_execution_error',
  'degeneracy_detected',
  'claim_mismatch',
  'infra_plan_error',
  'unknown',
];

// ============================================================
// GITHUB ACTIONS GENERATOR (Requirement 1-5)
// ============================================================

/**
 * Generate a complete GitHub Actions CI workflow.
 * @param {Object} ir - Pipeline IR
 * @param {string} platform - Target platform
 * @param {Object} [options]
 * @param {boolean} [options.includeInfraPlan] - Include terraform plan stage
 * @param {boolean} [options.includeRegression] - Include regression suite job
 * @param {string} [options.ciPlatform] - 'github' or 'gitlab'
 * @returns {string} YAML workflow content
 */
function generateGitHubActionsCI(ir, platform, options = {}) {
  const { includeInfraPlan = true, includeRegression = true } = options;
  const name = ir.name;
  const mainFile = getMainFile(ir, platform);

  return `# ============================================================
# CI Pipeline for: ${name}
# Platform: ${platform}
# Generated by EADD — wired to validation gate modules
# ============================================================
# Req 1: Same correctness gate as pre-return validation
# Req 2: Read-only (mocked infra only, plan-only for IaC)
# Req 3: Environment-aware (dev/stage/prod gating)
# Req 4: Failure classification on every failure
# Req 5: Regression suite as first-class CI job

name: Pipeline Validation CI — ${name}

on:
  push:
    branches: [main, develop, 'feature/**']
  pull_request:
    branches: [main, develop]
  release:
    types: [created]

env:
  PYTHON_VERSION: '3.11'
  PIPELINE_NAME: '${name}'
  TARGET_PLATFORM: '${platform}'

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# JOB 1: VALIDATE (runs on every push, blocks merge on failure)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
jobs:
  validate:
    name: "🔍 Validation Gate"
    runs-on: ubuntu-latest
    environment: dev
    outputs:
      failure_class: \${{ steps.classify.outputs.failure_class }}
    steps:
      - uses: actions/checkout@v4

      - name: Set up Python \${{ env.PYTHON_VERSION }}
        uses: actions/setup-python@v5
        with:
          python-version: \${{ env.PYTHON_VERSION }}
          cache: 'pip'

      - name: Install dependencies
        run: |
          pip install -r requirements.txt
          pip install ruff pytest moto[all] apache-beam[test] 2>/dev/null || true

      # ─── Stage 1: Lint ────────────────────────────────────
      - name: "Stage 1: Lint"
        id: lint
        run: |
          ruff check . --output-format=github || echo "::warning::Lint issues found"

      # ─── Stage 2: Repetition/Degeneracy Check ─────────────
      - name: "Stage 2: Repetition Check"
        id: repetition
        run: |
          python -c "
          import sys
          with open('${mainFile}') as f:
              lines = f.readlines()
          # Check consecutive repetition (3+)
          for i in range(2, len(lines)):
              if lines[i].strip() and lines[i] == lines[i-1] == lines[i-2]:
                  print(f'::error::Degeneracy: line {i+1} repeated 3+ times')
                  sys.exit(1)
          # Check cycle repetition
          for cycle_len in range(2, 9):
              for start in range(len(lines) - cycle_len * 5):
                  cycle = ''.join(lines[start:start+cycle_len])
                  repeats = 0
                  for pos in range(start, len(lines) - cycle_len, cycle_len):
                      if ''.join(lines[pos:pos+cycle_len]) == cycle:
                          repeats += 1
                      else:
                          break
                  if repeats >= 5:
                      print(f'::error::Cycle degeneracy: {cycle_len}-line block repeated {repeats}x')
                      sys.exit(1)
          print('✅ No repetition/degeneracy detected')
          "

      # ─── Stage 3: Syntax Check ────────────────────────────
      - name: "Stage 3: Syntax Check"
        id: syntax
        run: |
          python -m py_compile ${mainFile}
          echo "✅ Syntax valid"

      # ─── Stage 4: Platform-Import Allowlist ────────────────
      - name: "Stage 4: Platform Import Check"
        id: platform_imports
        run: |
          python -c "
          import ast, sys
          BLOCKED = ${getBlockedImportsJSON(platform)}
          with open('${mainFile}') as f:
              tree = ast.parse(f.read())
          violations = []
          for node in ast.walk(tree):
              if isinstance(node, ast.Import):
                  for alias in node.names:
                      for prefix in BLOCKED:
                          if alias.name.startswith(prefix):
                              violations.append(f'{alias.name} (blocked: {prefix})')
              elif isinstance(node, ast.ImportFrom) and node.module:
                  for prefix in BLOCKED:
                      if node.module.startswith(prefix):
                          violations.append(f'{node.module} (blocked: {prefix})')
          if violations:
              for v in violations:
                  print(f'::error::Platform import violation: {v}')
              sys.exit(1)
          print('✅ All imports consistent with ${platform}')
          "

      # ─── Stage 5: API-Existence Check ─────────────────────
      - name: "Stage 5: API Existence Check"
        id: api_check
        run: pytest tests/test_validation.py -v -k "api_exists" --tb=short || true

      # ─── Stage 6: Mocked Execution Tests ──────────────────
      - name: "Stage 6: Mocked Execution"
        id: mocked_exec
        run: pytest tests/ -v --tb=short
        env:
          # Mocked infra only (Req 2: never real accounts in CI)
          AWS_DEFAULT_REGION: us-east-1
          AWS_ACCESS_KEY_ID: testing
          AWS_SECRET_ACCESS_KEY: testing
          MOTO_ACCOUNT_ID: '123456789012'

      # ─── Stage 7: Claim-Consistency Check ──────────────────
      - name: "Stage 7: Claim Consistency"
        id: claims
        run: |
          python -c "
          import sys
          with open('${mainFile}') as f:
              code = f.read()
          # If README claims incremental, verify code has watermark logic
          try:
              with open('README.md') as r:
                  readme = r.read().lower()
              if 'incremental' in readme and 'where' not in code.lower() and 'is_incremental' not in code.lower():
                  print('::error::README claims incremental but code has no watermark filter')
                  sys.exit(1)
          except FileNotFoundError:
              pass
          print('✅ Claims match code')
          "

      # ─── Failure Classification (Req 4) ───────────────────
      - name: "Classify Failure"
        id: classify
        if: failure()
        run: |
          if [ "\${{ steps.repetition.outcome }}" == "failure" ]; then
            echo "failure_class=degeneracy_detected" >> \$GITHUB_OUTPUT
          elif [ "\${{ steps.syntax.outcome }}" == "failure" ]; then
            echo "failure_class=syntax_error" >> \$GITHUB_OUTPUT
          elif [ "\${{ steps.platform_imports.outcome }}" == "failure" ]; then
            echo "failure_class=platform_import_violation" >> \$GITHUB_OUTPUT
          elif [ "\${{ steps.api_check.outcome }}" == "failure" ]; then
            echo "failure_class=hallucinated_api" >> \$GITHUB_OUTPUT
          elif [ "\${{ steps.mocked_exec.outcome }}" == "failure" ]; then
            echo "failure_class=mocked_execution_error" >> \$GITHUB_OUTPUT
          elif [ "\${{ steps.claims.outcome }}" == "failure" ]; then
            echo "failure_class=claim_mismatch" >> \$GITHUB_OUTPUT
          else
            echo "failure_class=unknown" >> \$GITHUB_OUTPUT
          fi
          echo "::error::CI FAILURE CLASS: \${{ steps.classify.outputs.failure_class }}"

${includeRegression ? generateRegressionJob(platform) : ''}

${includeInfraPlan ? generateInfraPlanJob(ir, platform) : ''}

  # ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  # STAGE PROMOTION (Req 3: dev → stage → prod)
  # ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  promote-to-stage:
    name: "🚀 Promote to Stage"
    needs: [validate${includeRegression ? ', regression' : ''}]
    if: github.ref == 'refs/heads/main'
    runs-on: ubuntu-latest
    environment:
      name: staging
      # Req 2: Human approval required (GitHub Environment protection rule)
    steps:
      - run: echo "✅ Promoted to staging environment"

  promote-to-prod:
    name: "🏁 Promote to Production"
    needs: [promote-to-stage]
    if: startsWith(github.ref, 'refs/tags/v')
    runs-on: ubuntu-latest
    environment:
      name: production
      # Req 2+3: REQUIRES explicit human approval (never auto-promote)
    steps:
      - run: echo "✅ Promoted to production (human-approved)"
`;
}

// ============================================================
// REGRESSION SUITE JOB (Requirement 5)
// ============================================================

function generateRegressionJob(platform) {
  return `
  # ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  # JOB 2: REGRESSION SUITE (blocks release on known-bug regression)
  # ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  regression:
    name: "🧪 Regression Suite"
    runs-on: ubuntu-latest
    needs: [validate]
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: '3.11'
          cache: 'pip'
      - run: pip install -r requirements.txt && pip install pytest moto

      - name: "Run Regression Fixtures"
        run: |
          pytest tests/regression/ -v --tb=short
          # Known bugs that must NEVER reappear:
          # - airflow-no-generate-url
          # - databricks-no-boto3
          # - azure-no-boto3
          # - gcp-no-fake-beam-apis
        env:
          TARGET_PLATFORM: '${platform}'
`;
}

// ============================================================
// INFRA PLAN JOB (Requirement 2: plan-only, never apply)
// ============================================================

function generateInfraPlanJob(ir, platform) {
  return `
  # ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  # JOB 3: INFRASTRUCTURE PLAN (read-only, human reviews diff)
  # ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  infra-plan:
    name: "📋 Terraform Plan (read-only)"
    needs: [validate]
    if: github.ref == 'refs/heads/main' || github.event_name == 'pull_request'
    runs-on: ubuntu-latest
    environment: dev
    steps:
      - uses: actions/checkout@v4
      - uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: '1.7.0'

      - name: Terraform Init
        run: cd infra && terraform init -backend=false

      - name: "Terraform Plan (NEVER auto-apply)"
        run: |
          cd infra && terraform plan -no-color -out=tfplan
          echo "::notice::Infrastructure plan generated. Review before applying."
          echo "::notice::To apply: cd infra && terraform apply tfplan"
        # Req 2: Secrets from GitHub secret store ONLY
        env:
          AWS_ACCESS_KEY_ID: \${{ secrets.AWS_ACCESS_KEY_ID }}
          AWS_SECRET_ACCESS_KEY: \${{ secrets.AWS_SECRET_ACCESS_KEY }}
`;
}

// ============================================================
// GITLAB CI GENERATOR (alternative)
// ============================================================

function generateGitLabCI(ir, platform) {
  const name = ir.name;
  const mainFile = getMainFile(ir, platform);

  return `# GitLab CI for: ${name}
# Platform: ${platform}
# Generated by EADD

stages:
  - validate
  - regression
  - plan
  - stage
  - production

variables:
  PIPELINE_NAME: "${name}"
  TARGET_PLATFORM: "${platform}"

# ─── Validation Gate ─────────────────────────────────────────
validate:
  stage: validate
  image: python:3.11
  script:
    - pip install -r requirements.txt pytest ruff moto
    - ruff check .
    - python -m py_compile ${mainFile}
    - pytest tests/ -v
  rules:
    - if: \$CI_PIPELINE_SOURCE == "push"
    - if: \$CI_PIPELINE_SOURCE == "merge_request_event"

# ─── Regression Suite ────────────────────────────────────────
regression:
  stage: regression
  image: python:3.11
  script:
    - pip install -r requirements.txt pytest moto
    - pytest tests/regression/ -v
  needs: [validate]

# ─── Terraform Plan (never apply in CI) ─────────────────────
infra-plan:
  stage: plan
  image: hashicorp/terraform:1.7
  script:
    - cd infra && terraform init -backend=false
    - terraform plan -no-color
  rules:
    - if: \$CI_COMMIT_BRANCH == "main"
  needs: [validate]

# ─── Stage Deployment (manual gate) ─────────────────────────
deploy-stage:
  stage: stage
  script:
    - echo "Deploying to staging..."
  when: manual
  environment:
    name: staging
  needs: [regression]
  rules:
    - if: \$CI_COMMIT_BRANCH == "main"

# ─── Production (manual + tag-only) ─────────────────────────
deploy-prod:
  stage: production
  script:
    - echo "Deploying to production..."
  when: manual
  environment:
    name: production
  needs: [deploy-stage]
  rules:
    - if: \$CI_COMMIT_TAG
`;
}

// ============================================================
// HELPERS
// ============================================================

function getMainFile(ir, platform) {
  switch (platform) {
    case 'aws': return `dags/${ir.name}.py`;
    case 'databricks': return `notebooks/${ir.name}_bronze.py`;
    case 'gcp': return `pipelines/${ir.name}_beam.py`;
    case 'dbt': return `models/silver/stg_${ir.name}.sql`;
    case 'snowflake': return `sql/01_create_objects.sql`;
    case 'on_prem': return `dags/${ir.name}.py`;
    default: return `dags/${ir.name}.py`;
  }
}

function getBlockedImportsJSON(platform) {
  const blocked = {
    aws: '["azure", "google.cloud", "databricks"]',
    azure: '["boto3", "botocore", "awsglue", "google.cloud"]',
    gcp: '["boto3", "botocore", "azure", "awsglue"]',
    databricks: '["awsglue", "apache_beam"]',
    snowflake: '["boto3", "azure", "google.cloud", "pyspark"]',
    on_prem: '[]',
  };
  return blocked[platform] || '[]';
}

module.exports = {
  generateGitHubActionsCI,
  generateGitLabCI,
  FAILURE_TAXONOMY,
};
